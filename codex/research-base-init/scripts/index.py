#!/usr/bin/env python3
"""Regenerate a research base's index inside README.md's delimited block.

    scripts/index.py --base <base>
    scripts/index.py --base <base> --check

Derives the index table from each record's frontmatter, so the one place a
record's status and confidence are recorded is the record itself. Everything
between the BEGIN/END markers is owned by this script; everything outside them —
the pipeline description, the privacy split, the conventions — is hand-written
and never touched.

`--check` rewrites nothing and exits 1 if the index is stale, for use as a
pre-commit or review gate.

**The index lists every record in every tracked layer the base's `base.json`
declares** — exactly the population `validate_base.py` checks, read through its
`read_layers` and its `NON_RECORDS`, so the two cannot disagree about what a
record is. A layer keeps the name the base gives it, and each row links
`<layer>/<file>`. **A base without `base.json` is refused, not guessed at**: exit
2 with the validator's rule id, never a fallback to a `findings/` directory that
happens to exist. **So is a declared tracked layer missing from disk, but not an
untracked one**, which every fresh clone lacks and the index never reads. **So is
a base holding a record that is not UTF-8**: exit 2, naming every such record
with `record-not-utf8`, with or without `--check`, so `--check`'s exit 1 still
means *stale* and nothing else.

**The base is an argument, not a location.** This script used to derive it from
`__file__` and so only worked while it sat inside `research/` itself; it is
bundled into a skill payload now, where no such directory exists at any depth.
`validate_board.py --board` and `generate_index.py --board` take the directory
they operate on for the same reason, and this matches them, as does
`validate_base.py --base`.

Standard library only. Frontmatter is read through `validate_base.py`, the base's
one parser, which sits beside this script in every bundle that carries it.
"""

from __future__ import annotations

import argparse
import sys
from pathlib import Path

import validate_base

BEGIN = "<!-- BEGIN GENERATED INDEX -->"
END = "<!-- END GENERATED INDEX -->"

# Open work first, settled last — the same "actionable first" order the task
# board uses. Anything unrecognized sorts after the known ones, and so does a
# frozen record, which renders its regime in the status column.
STATUS_RANK = {"exploring": 0, "supported": 1, "promoted": 2}

def read_frontmatter(text: str) -> dict[str, str]:
    """Return the top-level scalar fields of a leading `--- ... ---` block.

    A view over `validate_base.read_frontmatter`, the base's one parser: list
    values are irrelevant to the index and are dropped here, so this module's
    contract is unchanged while nothing is parsed twice.
    """
    return {
        key: value
        for key, value in validate_base.read_frontmatter(text).items()
        if isinstance(value, str)
    }


def load_records(
    base: Path, layers: dict[str, dict]
) -> tuple[list[dict[str, str]], list[validate_base.Finding]]:
    """Every record in every tracked layer, each linked `<layer>/<file>`.

    Returned with the refusals for every record that does not decode, read
    through `validate_base.read_record`; any refusal means the rows are not to
    be rendered.
    """
    rows: list[dict[str, str]] = []
    refusals: list[validate_base.Finding] = []
    for directory in sorted(layers):
        if not layers[directory]["tracked"]:
            continue
        for path in sorted((base / directory).glob("*.md")):
            if path.name.lower() in validate_base.NON_RECORDS:
                continue
            text, unreadable = validate_base.read_record(base, path)
            if text is None:
                refusals.extend(unreadable)
                continue
            front = read_frontmatter(text)
            front["_path"] = f"{Path(directory).as_posix()}/{path.name}"
            front.setdefault("title", path.stem)
            rows.append(front)
    return rows, refusals


def render(rows: list[dict[str, str]]) -> str:
    ordered = sorted(
        rows,
        key=lambda r: (STATUS_RANK.get(r.get("status", ""), 99), r["title"].lower()),
    )
    lines = [
        BEGIN,
        "",
        f"*{len(ordered)} record(s). Generated by `scripts/index.py` — do not edit by hand.*",
        "",
        "| Record | Status | Confidence | Updated |",
        "| --- | --- | --- | --- |",
    ]
    for row in ordered:
        title = row.get("title", row["_path"])
        if row.get("regime") == "frozen":
            # A frozen record carries neither field by contract; `?` would read
            # as a defect in it rather than as its regime.
            status, confidence = "frozen", "—"
        else:
            status = row.get("status", "?")
            confidence = row.get("confidence", "?")
        updated = row.get("updated", "?")
        lines.append(
            f"| [{title}]({row['_path']}) | {status} | {confidence} | {updated} |"
        )
    lines += ["", END]
    return "\n".join(lines)


def splice(text: str, block: str) -> str:
    start, end = text.find(BEGIN), text.find(END)
    if start == -1 or end == -1 or end < start:
        raise SystemExit(
            f"README.md has no generated-index block. Add these markers where the "
            f"index belongs:\n\n{BEGIN}\n{END}"
        )
    return text[:start] + block + text[end + len(END) :]


def main() -> int:
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument(
        "--base",
        type=Path,
        required=True,
        help="research base holding base.json and README.md",
    )
    parser.add_argument(
        "--check",
        action="store_true",
        help="report staleness without writing; exit 1 if the index would change",
    )
    args = parser.parse_args()

    base = args.base
    if not base.is_dir():
        print(f"not a directory: {base}", file=sys.stderr)
        return 2

    # Refused with the validator's own rule ids, so a reader meets one
    # vocabulary for one failure whichever script reported it. An untracked
    # layer is exempt, as it is there: it is absent on every fresh clone, and
    # the index never reads it.
    layers, refusals = validate_base.read_layers(base)
    if layers is not None:
        refusals = [
            (directory, "layer-directory-missing",
             f"declared in {validate_base.BASE_FILE} but not on disk")
            for directory in sorted(layers)
            if layers[directory]["tracked"] and not (base / directory).is_dir()
        ]
    if refusals:
        for name, rule, message in refusals:
            print(f"{name}: [{rule}] {message}", file=sys.stderr)
        return 2

    readme = base / "README.md"
    if not readme.is_file():
        print(f"no README.md at {readme}", file=sys.stderr)
        return 2

    # Refused rather than indexed without them: an index silently missing a
    # record would pass `--check` while disagreeing with the validator.
    rows, refusals = load_records(base, layers)
    if refusals:
        for name, rule, message in refusals:
            print(f"{name}: [{rule}] {message}", file=sys.stderr)
        return 2

    current = readme.read_text(encoding="utf-8")
    updated = splice(current, render(rows))

    if args.check:
        if current != updated:
            print(f"STALE: {readme} index does not match the base's records")
            print(f"Run `index.py --base {base}` to regenerate.")
            return 1
        print("OK: index matches")
        return 0

    if current == updated:
        print("OK: index already matches")
        return 0
    with readme.open("w", encoding="utf-8", newline="\n") as handle:
        handle.write(updated)
    print(f"Regenerated the index in {readme}")
    return 0


if __name__ == "__main__":
    sys.exit(main())
